/* Builds js/clip-labels.js: the text side of the in-browser photo check, worked out once here
 * so the browser only has to download the (small) image model.
 *
 * Run only when you change a prompt below:
 *   npm i --no-save @huggingface/transformers@3.5.1
 *   node tools/make-clip-labels.mjs
 *
 * Keys starting with a project id (p4, p5, p2, p6) are what a correct photo should match.
 * Keys starting with x_ are common wrong photos; they give the model something else to pick.
 * Tested on 44 sample photos (Nov 2026): 22/26 right photos passed, 0/72 wrong-photo checks passed.
 */
import fs from "fs";
import path from "path";
import { fileURLToPath } from "url";
import { AutoTokenizer, CLIPTextModelWithProjection } from "@huggingface/transformers";

const MODEL = "Xenova/mobileclip_s0";
const PROMPTS = {
  p4: "small cloth sachets tied with string",
  p5: "a simple brown painting made with coffee",
  p2: "a small plant growing in a pot of soil",
  p6: "a jar of homemade body scrub",
  x_cat: "a cat", x_shoe: "shoes", x_cup: "a cup of coffee", x_room: "a classroom",
  x_stat: "pencils and stationery", x_grounds: "loose coffee grounds", x_person: "people",
  x_land: "a landscape", x_plant: "a large houseplant", x_art: "an old painting of a person",
  x_jar: "a jar of sugar", x_blur: "a blurry dark photo"
};

const tok = await AutoTokenizer.from_pretrained(MODEL);
const tm = await CLIPTextModelWithProjection.from_pretrained(MODEL, { dtype: "fp32" });
const labels = Object.keys(PROMPTS), embeds = [];
for (const k of labels) {
  const { text_embeds } = await tm(tok([PROMPTS[k]], { padding: "max_length", truncation: true }));
  const v = Array.from(text_embeds.data), n = Math.hypot(...v);
  embeds.push(v.map(x => +(x / n).toFixed(5)));
}
const out = path.join(path.dirname(fileURLToPath(import.meta.url)), "..", "js", "clip-labels.js");
fs.writeFileSync(out,
  "/* Generated by tools/make-clip-labels.mjs. Do not edit by hand. */\n" +
  "var CLIP_LABELS = " + JSON.stringify({ model: MODEL, prompts: PROMPTS, labels, embeds }) + ";\n");
console.log("wrote", out, labels.length, "labels x", embeds[0].length, "dims");
